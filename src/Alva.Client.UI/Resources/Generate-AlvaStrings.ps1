<#
.SYNOPSIS
    Generates Resources/AlvaStrings.Designer.cs from AppStrings.resx and AppStrings.ru.resx.

.DESCRIPTION
    Alva keeps one neutral English resource (AppStrings.resx) and one Russian resource
    (AppStrings.ru.resx). Static keys are symbolic identifiers in the form Area_Name and become
    static properties on AlvaStrings; the dynamic plural.* and reason.* keys stay out of the
    generated class because callers resolve them at run time.

    Run this script after adding, renaming or removing a static key. The generated file is
    committed, matching the Flare.Gallery approach, so a build without Visual Studio still sees
    the typed API.
#>
[CmdletBinding()]
param()

$resources = $PSScriptRoot
$enPath = Join-Path $resources 'AppStrings.resx'
$ruPath = Join-Path $resources 'AppStrings.ru.resx'
$outPath = Join-Path $resources 'AlvaStrings.Designer.cs'

function Read-Entries([string] $path) {
    [xml] $doc = Get-Content -LiteralPath $path -Raw -Encoding UTF8
    $entries = foreach ($node in $doc.root.data) {
        if ($null -eq $node.name) { continue }
        $value = if ($null -ne $node.value) { [string] $node.value } else { '' }
        [pscustomobject]@{ Name = [string] $node.name; Value = $value }
    }
    return @($entries)
}

function Test-DynamicKey([string] $name) {
    return $name.StartsWith('plural.', [System.StringComparison]::Ordinal) -or
           $name.StartsWith('reason.', [System.StringComparison]::Ordinal)
}

function Escape-Summary([string] $text) {
    $flat = ($text -replace '\s+', ' ').Trim()
    if ($flat.Length -gt 160) { $flat = $flat.Substring(0, 157) + '...' }
    return $flat.Replace('&', '&amp;').Replace('<', '&lt;').Replace('>', '&gt;')
}

$en = Read-Entries $enPath
$ru = Read-Entries $ruPath
$enStatic = @($en | Where-Object { -not (Test-DynamicKey $_.Name) })
$ruStatic = @($ru | Where-Object { -not (Test-DynamicKey $_.Name) })
$enDynamic = @($en | Where-Object { Test-DynamicKey $_.Name })
$ruDynamic = @($ru | Where-Object { Test-DynamicKey $_.Name })

$enKeys = @($enStatic.Name)
$ruKeys = @($ruStatic.Name)
$missingRu = @($enKeys | Where-Object { $ruKeys -notcontains $_ })
$missingEn = @($ruKeys | Where-Object { $enKeys -notcontains $_ })
if ($missingRu.Count -gt 0 -or $missingEn.Count -gt 0) {
    throw "Static keys differ. Missing in ru: $($missingRu -join ', '). Missing in en: $($missingEn -join ', ')."
}

$dynamicEnKeys = @($enDynamic.Name | Sort-Object)
$dynamicRuKeys = @($ruDynamic.Name | Sort-Object)
if (($dynamicEnKeys -join "`n") -ne ($dynamicRuKeys -join "`n")) {
    throw 'Dynamic plural.* / reason.* key sets differ between the neutral and Russian resources.'
}

$invalid = @($enKeys | Where-Object { $_ -notmatch '^[A-Za-z][A-Za-z0-9]*_[A-Za-z0-9_]+$' })
if ($invalid.Count -gt 0) {
    throw "Static resource keys must be C# identifiers in the form Area_Name. Invalid: $($invalid -join ', ')."
}
$duplicates = @($enStatic | Group-Object Name | Where-Object { $_.Count -gt 1 } | ForEach-Object { $_.Name })
if ($duplicates.Count -gt 0) {
    throw "Duplicate static resource keys: $($duplicates -join ', ')."
}

$builder = [System.Text.StringBuilder]::new()
[void] $builder.AppendLine('// <auto-generated>')
[void] $builder.AppendLine('//     Generated from AppStrings.resx by Resources/Generate-AlvaStrings.ps1.')
[void] $builder.AppendLine('//     Do not edit this file by hand: change the resx entries and rerun the script.')
[void] $builder.AppendLine('// </auto-generated>')
[void] $builder.AppendLine('#nullable enable')
[void] $builder.AppendLine('using System.CodeDom.Compiler;')
[void] $builder.AppendLine('using System.Diagnostics;')
[void] $builder.AppendLine('using System.Diagnostics.CodeAnalysis;')
[void] $builder.AppendLine('using System.Globalization;')
[void] $builder.AppendLine('using System.Resources;')
[void] $builder.AppendLine('using System.Runtime.CompilerServices;')
[void] $builder.AppendLine()
[void] $builder.AppendLine('namespace Alva.Client;')
[void] $builder.AppendLine()
[void] $builder.AppendLine('/// <summary>Typed access to the application strings in the current interface language.</summary>')
[void] $builder.AppendLine('[GeneratedCode("Alva.Localization", "1.0")]')
[void] $builder.AppendLine('[DebuggerNonUserCode]')
[void] $builder.AppendLine('[CompilerGenerated]')
[void] $builder.AppendLine('public static class AlvaStrings')
[void] $builder.AppendLine('{')
[void] $builder.AppendLine('    private static readonly ResourceManager Manager = CreateManager();')
[void] $builder.AppendLine()
[void] $builder.AppendLine('    /// <summary>Overrides the lookup culture; null follows CultureInfo.CurrentUICulture.</summary>')
[void] $builder.AppendLine('    public static CultureInfo? Culture { get; set; }')
[void] $builder.AppendLine()
[void] $builder.AppendLine('    private static ResourceManager CreateManager()')
[void] $builder.AppendLine('    {')
[void] $builder.AppendLine('        var manager = new ResourceManager("Alva.Client.AppStrings", typeof(AppStrings).Assembly);')
[void] $builder.AppendLine('        manager.IgnoreCase = true;')
[void] $builder.AppendLine('        return manager;')
[void] $builder.AppendLine('    }')
[void] $builder.AppendLine()
[void] $builder.AppendLine('    private static string Get(string key) =>')
[void] $builder.AppendLine('        Manager.GetString(key, Culture ?? CultureInfo.CurrentUICulture) ?? string.Empty;')

foreach ($entry in $enStatic) {
    [void] $builder.AppendLine()
    [void] $builder.AppendLine("    /// <summary>$(Escape-Summary $entry.Value)</summary>")
    [void] $builder.AppendLine("    public static string $($entry.Name) => Get(""$($entry.Name)"");")
}

[void] $builder.AppendLine('}')
$encoding = [System.Text.UTF8Encoding]::new($false)
[System.IO.File]::WriteAllText($outPath, $builder.ToString(), $encoding)
Write-Host "Generated $outPath with $($enStatic.Count) static strings and $($enDynamic.Count) dynamic keys."
